"""Generate small kernel-checkable chunks, never trusted computational proofs.

Run with Python's standard library. Every emitted claim is subsequently proved
by Lean `decide`; the generator's correctness is outside the trusted proof base.
The split avoids one enormous kernel reduction cache on ordinary CI machines.
"""
from itertools import product
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent


def emit(name, lines, check):
    content = "\n".join(lines)
    path = ROOT / name
    if check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit(f"Stale generated certificate: {name}")
    else:
        path.write_text(content, encoding="utf-8", newline="\n")


def generate(check=False):
    lines = ["import FiveObjectData", "", "-- Generated by generate_certificates.py; every chunk is kernel checked.",
             "set_option maxRecDepth 1000000", "set_option maxHeartbeats 0", "",
             "namespace FiniteCongruenceChecks.FiveObject", ""]
    for ns in ("A", "B"):
        lines += [f"namespace {ns}", ""]
        for prefix in product(("false", "true"), repeat=5):
            suffix = "".join("1" if x == "true" else "0" for x in prefix)
            shape = ",".join((*prefix, "b5", "b6", "b7", "b8", "b9"))
            lines += [f"private theorem classification_{suffix} : ∀ b5 b6 b7 b8 b9 : Bool,",
                      f"    IsCongruence ops (relation ({shape})) ↔",
                      f"      ∃ a : Fin 8, Same (relation ({shape})) (theta a) := by decide", ""]
        lines += ["theorem finite_classification : ∀ s : Shape,",
                  "    IsCongruence ops (relation s) ↔ ∃ a : Fin 8, Same (relation s) (theta a) := by",
                  "  rintro ⟨b0,b1,b2,b3,b4,b5,b6,b7,b8,b9⟩",
                  "  cases b0 <;> cases b1 <;> cases b2 <;> cases b3 <;> cases b4"]
        for prefix in product((0, 1), repeat=5):
            suffix = "".join(map(str, prefix))
            lines.append(f"  · exact classification_{suffix} b5 b6 b7 b8 b9")
        lines += ["", f"end {ns}", ""]
    lines += ["end FiniteCongruenceChecks.FiveObject", ""]
    emit("FiveObjectClassification.lean", lines, check)

    lines = ["import FiveObjectData", "", "-- Generated by generate_certificates.py; every chunk is kernel checked.",
             "set_option maxRecDepth 1000000", "set_option maxHeartbeats 0", "",
             "namespace FiniteCongruenceChecks.FiveObject", "", "namespace A", "",
             "abbrev Profile := Bool × Bool × Bool × Bool",
             "def profile (f : V → V) : Profile :=",
             "  (decide (Preserves f (obstruction 0)), decide (Preserves f (obstruction 1)),",
             "    decide (Preserves f (obstruction 2)), decide (Preserves f (obstruction 3)))",
             "def profileAt (p : Profile) (i : Fin 4) : Bool :=",
             "  match i.val with | 0 => p.1 | 1 => p.2.1 | 2 => p.2.2.1 | _ => p.2.2.2",
             "def AllowedProfile (p : Profile) : Prop :=",
             "  p = (false,true,true,true) ∨ p = (true,false,false,true) ∨",
             "  p = (true,false,true,false) ∨ p = (true,true,false,false) ∨ p = (true,true,true,true)",
             "instance (p : Profile) : Decidable (AllowedProfile p) := inferInstanceAs",
             "  (Decidable (p = (false,true,true,true) ∨ p = (true,false,false,true) ∨",
             "    p = (true,false,true,false) ∨ p = (true,true,false,false) ∨ p = (true,true,true,true)))", ""]
    for ns in ("A", "B"):
        if ns == "B":
            lines += ["namespace B", ""]
        for prefix in product(range(5), repeat=3):
            suffix = "".join(map(str, prefix))
            table = ",".join((*map(str, prefix), "d", "e"))
            conclusion = (f"AllowedProfile (profile (table ({table})))" if ns == "A" else
                          f"Preserves (table ({table})) (obstruction 0) ∨ Preserves (table ({table})) (obstruction 1)")
            lines += [f"private theorem obstruction_{suffix} : ∀ d e : V,",
                      f"    PreservesFamily theta (table ({table})) → {conclusion} := by decide", ""]
        name = "profile_certificate" if ns == "A" else "obstruction_certificate"
        conclusion = ("AllowedProfile (profile (table (a,b,c,d,e)))" if ns == "A" else
                      "Preserves (table (a,b,c,d,e)) (obstruction 0) ∨ Preserves (table (a,b,c,d,e)) (obstruction 1)")
        lines += ["/-- Covers all 3125 unary maps; arbitrary functions enter through table_complete. -/",
                  f"theorem {name} : ∀ a b c d e : V,",
                  f"    PreservesFamily theta (table (a,b,c,d,e)) → {conclusion} := by",
                  "  intro a b c",
                  "  rcases fin5_cases a with rfl | rfl | rfl | rfl | rfl",
                  "  all_goals rcases fin5_cases b with rfl | rfl | rfl | rfl | rfl",
                  "  all_goals rcases fin5_cases c with rfl | rfl | rfl | rfl | rfl"]
        for prefix in product(range(5), repeat=3):
            suffix = "".join(map(str, prefix))
            lines.append(f"  · exact obstruction_{suffix}")
        lines += ["", f"end {ns}", ""]
    lines += ["end FiniteCongruenceChecks.FiveObject", ""]
    emit("FiveObjectObstructions.lean", lines, check)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ; never rewrite them.")
    args = parser.parse_args()
    generate(check=args.check)
    print("Generated certificates are current." if args.check else "Generated classification and obstruction certificates.")
