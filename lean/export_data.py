"""Generate the N5/B3 Lean data module from the recorded JSON certificates.

Run ``python lean/export_data.py`` to regenerate, or add ``--check`` to reject
stale output without writing. This exports data, not a proof: Lean checks the
lattice laws, congruence classification and upstream witness separately.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from verify_witness import SOURCE, validate_lattice

NAMES = (("N5", 5), ("B3", 8))


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def table(name: str, domain: str, codomain: str, rows: list) -> str:
    def literal(value):
        return str(value).lower() if type(value) is bool else str(value)
    cases = [f"  | {i}, {j} => {literal(v)}"
             for i, row in enumerate(rows) for j, v in enumerate(row)]
    fallback = "false" if codomain == "Bool" else "0"
    return (f"def {name} (x y : {domain}) : {codomain} :=\n"
            "  match x.val, y.val with\n" + "\n".join(cases)
            + f"\n  | _, _ => {fallback}\n")


def render(root: Path = ROOT) -> str:
    """Read and validate inputs before producing any output."""
    minimum_path = root / "evidence/minimized-algebras.json"
    minimum_bytes = minimum_path.read_bytes()
    minimum = json.loads(minimum_bytes)
    require(minimum.get("passed") is True, "operation evidence did not pass")
    records = minimum["certificates"]
    names = [record["certificate"] for record in records]
    require(len(names) == len(set(names)), "duplicate operation certificate record")
    operations = {record["certificate"]: record for record in records}
    hashes = {"evidence/minimized-algebras.json": hashlib.sha256(minimum_bytes).hexdigest()}
    blocks = []
    for name, count in NAMES:
        relative = f"evidence/{name}-witness.json"
        raw = (root / relative).read_bytes()
        hashes[relative] = hashlib.sha256(raw).hexdigest()
        data = json.loads(raw)
        require(data.get("schema_version") == 1, f"{name}: unsupported certificate schema")
        require(all(data["source"].get(key) == SOURCE[key]
                    for key in ("repository", "revision", "path", "sha256")),
                f"{name}: upstream source differs")
        lattice = data["lattice"]
        validation = validate_lattice(lattice)
        require(lattice["name"] == name and validation["element_count"] == count,
                f"{name}: unexpected lattice identity or size")
        color = data["color"]
        require(isinstance(color, list) and len(color) == 4
                and all(isinstance(row, list) and len(row) == 4 for row in color)
                and all(type(v) is int and 0 <= v < count for row in color for v in row),
                f"{name}: expected a four-point color matrix")
        record = operations[f"{name}-witness.json"]
        require(record.get("passed") is True, f"{name}: operation evidence did not pass")
        require(record["certificate_sha256"] == hashes[relative],
                f"{name}: operation evidence binds a different certificate")
        ops = record["selected_unary_operations"]
        require(isinstance(ops, list) and len(ops) == 2
                and all(isinstance(op, list) and len(op) == 4 for op in ops)
                and all(type(v) is int and 0 <= v < 4 for op in ops for v in op),
                f"{name}: expected two total operations on four points")
        fin = f"Fin {count}"
        parts = [f"namespace {name}\n", table("le", fin, "Bool", lattice["leq"]),
                 table("color", "V", fin, color)]
        for index, op in enumerate(ops, 1):
            cases = [f"  | {i} => {op[i]}" for i in range(3)] + [f"  | _ => {op[3]}"]
            parts.append(f"def op{index} (x : V) : V :=\n  match x.val with\n"
                         + "\n".join(cases) + "\n")
        parts += [table("join", fin, fin, lattice["join"]),
                  table("meet", fin, fin, validation["derived_meet"]),
                  f"def bottom : {fin} := {lattice['bottom']}\n", f"end {name}\n"]
        blocks.append("\n".join(parts))
    provenance = "\n".join(f"{path}: {digest}" for path, digest in sorted(hashes.items()))
    return ("import Std\n\n/-!\nGenerated by `python lean/export_data.py`; do not edit by hand.\n"
            "Data only. Formal claims are checked in the importing proof modules.\n"
            "Meets are derived from the JSON order and checked again by Lean lattice laws.\n\n"
            + provenance + "\n-/\n\nnamespace FiniteCongruenceChecks\n\nabbrev V := Fin 4\n\n"
            + "\n".join(blocks) + "\nend FiniteCongruenceChecks\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render().encode("utf-8")
    destination = ROOT / "lean/CertificateData.lean"
    if args.check:
        require(destination.exists() and destination.read_bytes() == expected,
                "Lean certificate data is stale; run python lean/export_data.py")
        print("Lean certificate export is current (N5 and B3).")
    else:
        destination.write_bytes(expected)
        print("Generated lean/CertificateData.lean from the recorded N5/B3 evidence.")


if __name__ == "__main__":
    main()
