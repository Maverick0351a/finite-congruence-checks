"""Independently exhaust and check the finite congruence atlas on 1..4 points.

No project mathematics or atlas-generator code is imported. Partitions come
from all label assignments. Every candidate family is tested using the
Con(End(E)) closure, rather than intersections generated by a search queue.
All vertex relabelings and all poset labelings within invariant classes are
enumerated. Operation lower bounds exhaust all zero, one, and two-map choices.
This is a finite Python cross-check, not a Lean proof or a novelty claim.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from functools import lru_cache
import hashlib
from itertools import combinations, permutations, product
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
HASH_ENCODING = "SHA-256 of UTF-8 file bytes with CRLF normalized to LF; no other byte changes."
SOURCES = {"evidence/operation-minima-audit.json", "evidence/search-results.json",
           "minimize_operations.py", "scripts/audit_operation_minima.py"}


def require(condition, message):
    """Keep all checks active even if Python is invoked with -O."""
    if not condition:
        raise ValueError(message)


def text_hash(path):
    return hashlib.sha256(Path(path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def normalize(labels):
    rename = {}
    return tuple(rename.setdefault(label, len(rename)) for label in labels)


def partitions(n):
    return sorted({normalize(labels) for labels in product(range(n), repeat=n)})


def preserves(operation, partition):
    return all(partition[x] != partition[y] or
               partition[operation[x]] == partition[operation[y]]
               for x in range(len(partition)) for y in range(x))


def refines(first, second):
    return all(first[x] != first[y] or second[x] == second[y]
               for x in range(len(first)) for y in range(x))


def order_matrix(family):
    return tuple(tuple(refines(first, second) for second in family) for first in family)


def covering_pairs(matrix):
    return [(i, j) for i in range(len(matrix)) for j in range(len(matrix))
            if i != j and matrix[i][j] and not any(
                k not in (i, j) and matrix[i][k] and matrix[k][j]
                for k in range(len(matrix)))]


@lru_cache(maxsize=None)
def canonical_order(matrix):
    """Literal exhaustive canonical labeling within isomorphism invariants.

    The two counts are numbers of elements below and above each node. Any
    isomorphism preserves them, so the restricted permutations still include
    every possible isomorphism. This does not use the builder's matching code.
    """
    size = len(matrix)
    invariants = [(sum(row[i] for row in matrix), sum(matrix[i])) for i in range(size)]
    classes = [tuple(i for i, value in enumerate(invariants) if value == invariant)
               for invariant in sorted(set(invariants))]
    candidates = product(*(tuple(permutations(group)) for group in classes))
    return min(bytes(matrix[i][j] for i in sequence for j in sequence)
               for groups in candidates for sequence in [sum(groups, ())])


def orbit(family, n):
    return {tuple(sorted(normalize(p[relabel[x]] for x in range(n)) for p in family))
            for relabel in permutations(range(n))}


def operation_minimum(family_mask, all_mask, operation_masks):
    """Exhaust combinations of distinct map effects, without a cover solver."""
    if family_mask == all_mask:
        return 0
    allowed = sorted({mask for mask in operation_masks if mask & family_mask == family_mask})
    if family_mask in allowed:
        return 1
    if any(first & second == family_mask for first, second in combinations(allowed, 2)):
        return 2
    raise ValueError("Derived representable family requires more than two operations")


@lru_cache(maxsize=1)
def independent_census():
    """Enumerate every candidate subset and retain exactly the closed ones."""
    carriers = {}
    for n in range(1, 5):
        eqs = partitions(n)
        maps = list(product(range(n), repeat=n))
        all_maps = (1 << len(maps)) - 1
        all_relations = (1 << len(eqs)) - 1
        preserving_maps = [sum(1 << i for i, f in enumerate(maps) if preserves(f, p))
                           for p in eqs]
        operation_masks = [sum(1 << j for j, p in enumerate(eqs) if preserves(f, p))
                           for f in maps]
        mandatory = {eqs.index(tuple(range(n))), eqs.index((0,) * n)}
        optional = [i for i in range(len(eqs)) if i not in mandatory]
        families = {}
        for choices in product((False, True), repeat=len(optional)):
            selected = sorted(mandatory | {i for i, chosen in zip(optional, choices) if chosen})
            target_mask = sum(1 << i for i in selected)
            endomorphisms = all_maps
            for i in selected:
                endomorphisms &= preserving_maps[i]
            closure = sum(1 << i for i, allowed in enumerate(preserving_maps)
                          if endomorphisms & allowed == endomorphisms)
            if closure == target_mask:
                family = tuple(eqs[i] for i in selected)
                families[family] = operation_minimum(target_mask, all_relations, operation_masks)
        orbits = {}
        uncovered = set(families)
        while uncovered:
            family = min(uncovered)
            members = orbit(family, n)
            require(members <= families.keys(), f"n={n}: closure census is not relabeling invariant")
            representative = min(members)
            minima = {families[member] for member in members}
            require(len(minima) == 1, f"n={n}: operation minima changed under relabeling")
            orbits[representative] = {"members": members, "minimum": minima.pop(),
                                     "signature": canonical_order(order_matrix(representative))}
            uncovered -= members
        carriers[n] = {"partitions": eqs, "families": families, "orbits": orbits,
                       "all_unary_maps": len(maps), "candidate_subsets": 2 ** len(optional)}
    return carriers


def named_signatures():
    named = {}
    for size in range(2, 5):
        named[f"C{size}"] = canonical_order(tuple(tuple(i <= j for j in range(size)) for i in range(size)))
    for rank in (2, 3):
        named[f"B{rank}"] = canonical_order(tuple(tuple(i & j == i for j in range(2 ** rank))
                                                 for i in range(2 ** rank)))
    for atoms in (3, 4):
        size = atoms + 2
        named[f"M{atoms}"] = canonical_order(tuple(tuple(i == j or i == 0 or j == size - 1
                                                         for j in range(size)) for i in range(size)))
    named["N5"] = canonical_order(tuple(tuple(i == j or i == 0 or j == 4 or (i == 1 and j == 2)
                                              for j in range(5)) for i in range(5)))
    return named


def check(data, root=ROOT):
    """Validate an atlas object and return a deterministic review receipt."""
    require(data.get("schema_version") == 1, "unsupported atlas schema_version")
    derived = independent_census()
    entries = data.get("entries")
    require(isinstance(entries, list), "entries must be a list")
    require(all(isinstance(entry, dict) for entry in entries), "entries must be objects")
    entry_ids = [entry.get("id") for entry in entries]
    require(all(isinstance(value, str) and value for value in entry_ids), "invalid entry id")
    require(len(set(entry_ids)) == len(entry_ids), "duplicate embedding id")
    observed = defaultdict(set)
    observed_signatures = {}
    receipts = []
    names = named_signatures()
    for entry in entries:
        identifier = entry["id"]
        n = entry.get("carrier_size")
        require(type(n) is int and n in derived, f"{identifier}: invalid carrier_size")
        raw_family = entry.get("partitions")
        require(isinstance(raw_family, list) and raw_family, f"{identifier}: missing partitions")
        require(all(isinstance(p, list) and len(p) == n and all(type(x) is int for x in p)
                    for p in raw_family), f"{identifier}: malformed partition")
        family = tuple(tuple(p) for p in raw_family)
        require(len(set(family)) == len(family), f"{identifier}: duplicate partition")
        require(all(p in derived[n]["partitions"] for p in family), f"{identifier}: invalid partition")
        key = tuple(sorted(family))
        require(key in derived[n]["families"], f"{identifier}: family is not representable")
        canonical = min(orbit(key, n))
        require(canonical not in observed[n], f"{identifier}: duplicate embedding orbit")
        observed[n].add(canonical)
        expected = derived[n]["orbits"][canonical]
        require(type(entry.get("orbit_size")) is int and entry["orbit_size"] == len(expected["members"]),
                f"{identifier}: incorrect orbit_size")
        require(type(entry.get("minimum_unary_operations")) is int and
                entry["minimum_unary_operations"] == expected["minimum"],
                f"{identifier}: incorrect minimum_unary_operations")
        operations = entry.get("operations")
        require(isinstance(operations, list) and all(isinstance(f, list) and len(f) == n and
                all(type(x) is int and 0 <= x < n for x in f) for f in operations),
                f"{identifier}: malformed operations")
        require(len(operations) == expected["minimum"], f"{identifier}: operation list is not minimum size")
        recovered = {p for p in derived[n]["partitions"] if all(preserves(f, p) for f in operations)}
        require(recovered == set(family), f"{identifier}: operations do not recover exact family")
        matrix = order_matrix(family)
        require(entry.get("order") == [list(row) for row in matrix], f"{identifier}: incorrect order matrix")
        require(entry.get("covers") == [list(pair) for pair in covering_pairs(matrix)],
                f"{identifier}: incorrect covering pairs")
        signature = expected["signature"]
        observed_signatures[identifier] = signature
        targets = entry.get("named_targets")
        require(isinstance(targets, list) and len(set(targets)) == len(targets),
                f"{identifier}: malformed named_targets")
        require(set(targets) == {name for name, shape in names.items() if shape == signature},
                f"{identifier}: named targets do not match its poset")
        require(entry.get("name") == (targets[0] if targets else f"Shape {entry.get('abstract_type')}"),
                f"{identifier}: incorrect display name")
        receipts.append({"id": identifier, "carrier_size": n, "orbit_size": len(expected["members"]),
                         "minimum_unary_operations": expected["minimum"],
                         "poset_canonical_sha256": hashlib.sha256(signature).hexdigest(),
                         "exact_operations_order_and_covers": True})
    for n in derived:
        require(observed[n] == derived[n]["orbits"].keys(), f"n={n}: incomplete embedding orbit coverage")
    type_rows = data.get("abstract_types")
    require(isinstance(type_rows, list) and all(isinstance(row, dict) for row in type_rows),
            "abstract_types must be a list of objects")
    type_ids = [row.get("id") for row in type_rows]
    require(all(isinstance(value, str) and value for value in type_ids) and len(set(type_ids)) == len(type_ids),
            "invalid or duplicate abstract type id")
    membership = {}
    signatures_to_types = {}
    entry_by_id = {entry["id"]: entry for entry in entries}
    for row in type_rows:
        members = row.get("embedding_ids")
        require(isinstance(members, list) and members and len(set(members)) == len(members),
                f"{row['id']}: empty or duplicate type membership")
        require(all(member in entry_by_id for member in members), f"{row['id']}: unknown embedding id")
        signatures = {observed_signatures[member] for member in members}
        require(len(signatures) == 1, f"{row['id']}: non-isomorphic embeddings grouped together")
        signature = signatures.pop()
        require(signature not in signatures_to_types, f"{row['id']}: isomorphic embeddings split across types")
        signatures_to_types[signature] = row["id"]
        require(all(len(entry_by_id[member]["partitions"]) == row.get("lattice_elements") for member in members),
                f"{row['id']}: incorrect lattice_elements")
        for member in members:
            require(member not in membership, f"{member}: belongs to multiple abstract types")
            membership[member] = row["id"]
            require(entry_by_id[member].get("abstract_type") == row["id"], f"{member}: abstract_type mismatch")
            require(entry_by_id[member].get("name") == row.get("name"), f"{member}: name mismatch")
    require(membership.keys() == entry_by_id.keys(), "abstract type membership omits entries")
    summaries = []
    for n, value in derived.items():
        summaries.append({"carrier_size": n, "labeled_relation_families": len(value["families"]),
                          "embedding_orbits": len(value["orbits"]),
                          "abstract_types": len({row["signature"] for row in value["orbits"].values()})})
    require(data.get("carrier_summary") == summaries, "carrier_summary differs from independent census")
    hashes = data.get("source_sha256")
    require(isinstance(hashes, dict) and set(hashes) == SOURCES, "source_sha256 registry is incomplete")
    require(data.get("hash_encoding") == HASH_ENCODING, "unsupported source hash_encoding")
    for name, expected_hash in hashes.items():
        path = (Path(root) / name).resolve()
        require(path.is_relative_to(Path(root).resolve()), "source hash path escapes repository")
        require(path.is_file() and text_hash(path) == expected_hash, f"source hash mismatch: {name}")
    generator = Path(root) / "scripts/build_atlas_data.py"
    require(generator.is_file() and text_hash(generator) == data.get("generator_sha256"), "generator hash mismatch")
    return {"schema_version": 1, "passed": True, "hash_encoding": HASH_ENCODING,
            "checker_sha256": text_hash(__file__),
            "method": "Independent assignment partitions, Con(End(E)) subset exhaustion, literal pair preservation, exhaustive map-pair minima, all relabelings, and exhaustive invariant-class poset labeling.",
            "limitations": "Finite Python cross-check; not a Lean proof and no novelty claim.",
            "carrier_summary": summaries,
            "candidate_subsets_by_carrier": {str(n): row["candidate_subsets"] for n, row in derived.items()},
            "all_unary_maps_by_carrier": {str(n): row["all_unary_maps"] for n, row in derived.items()},
            "total_embedding_orbits": len(entries), "abstract_types_across_carriers": len(signatures_to_types),
            "entries": receipts}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--atlas", type=Path, default=ROOT / "evidence/atlas.json")
    parser.add_argument("--out", type=Path, help="Write deterministic independent-check receipt")
    parser.add_argument("--check-receipt", type=Path,
                        help="Require a saved receipt to match the recomputed receipt (CRLF normalized)")
    args = parser.parse_args(argv)
    try:
        data = json.loads(args.atlas.read_text(encoding="utf-8"))
        receipt = check(data)
        receipt["atlas_sha256"] = text_hash(args.atlas)
        receipt_text = json.dumps(receipt, indent=2) + "\n"
        if args.check_receipt:
            saved = args.check_receipt.read_bytes().replace(b"\r\n", b"\n")
            require(saved == receipt_text.encode("utf-8"), "saved review receipt is stale or modified")
        if args.out:
            args.out.parent.mkdir(parents=True, exist_ok=True)
            args.out.write_text(receipt_text, encoding="utf-8", newline="\n")
        print(json.dumps({key: receipt[key] for key in ("passed", "carrier_summary", "total_embedding_orbits", "abstract_types_across_carriers")}, indent=2))
        return 0
    except (ValueError, OSError, KeyError, TypeError) as error:
        print(f"Atlas check failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
